import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import * as auth from '../controllers/auth.js';
import * as projects from '../controllers/projects.js';
import * as tasks from '../controllers/tasks.js';
import { authenticated } from '../middleware/auth.js';
export const router = Router();
const limiter = rateLimit({ windowMs:15*60*1000,limit:30,standardHeaders:'draft-8',legacyHeaders:false,message:{ error:'Pārāk daudz mēģinājumu. Mēģiniet pēc 15 minūtēm.' } });
router.get('/auth/me',auth.me);
router.post('/auth/register',limiter,auth.register);
router.post('/auth/login',limiter,auth.login);
router.use(authenticated);
router.post('/auth/logout',auth.logout);
router.put('/profile',auth.profile);
router.put('/profile/password',limiter,auth.password);
router.get('/projects',projects.list);
router.post('/projects',projects.create);
router.get('/projects/:id',projects.get);
router.put('/projects/:id',projects.update);
router.delete('/projects/:id',projects.remove);
router.get('/projects/:id/members',projects.members);
router.post('/projects/:id/members',projects.addMember);
router.delete('/projects/:id/members/:userId',projects.removeMember);
router.get('/projects/:id/tasks',tasks.list);
router.post('/projects/:id/tasks',tasks.create);
router.get('/tasks/my',tasks.my);
router.put('/tasks/:id',tasks.update);
router.patch('/tasks/:id/status',tasks.status);
router.delete('/tasks/:id',tasks.remove);
router.get('/dashboard/stats',tasks.dashboard);

